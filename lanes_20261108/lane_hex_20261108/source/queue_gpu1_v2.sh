#!/bin/bash
# HEX lane GPU 1 queue v2 (2026-11-08). Runs jobs from jobs_gpu1.tsv (NAME<TAB>python args, run from the lane folder with
# CUDA_VISIBLE_DEVICES=1) next to the backbone lane's CPSAM (coordinator OK: at most 2 jobs, ~4 GB each, never touch CPSAM).
# Concurrency is read every loop from slots_gpu1.txt (default 1), so it can change without a restart.
# A job is done when logs/<NAME>.log exists (started) - lines may be appended while this runs (write a new file, then mv).
# The keepalive starts only when nothing is left AND the CPSAM pid (arg 1) is gone; it is stopped by its pid before the next job.
# STOP_QUEUE file stops the runner (running jobs keep going). Do not edit this file while it runs.
LANE=/workspace/clear-ec-research/experiments/lane_hex_20261108; cd $LANE
CPSAM=${1:-0}; PY=/workspace/venv/bin/python; KA=/workspace/clear-ec-research/experiments/phase2_pooling_replication_20261026/gpu_keepalive.py
log() { echo "$(date -u +%FT%TZ) $*" >> $LANE/logs/queue_gpu1.log; }
echo $$ > $LANE/queue_gpu1.pid; log "queue v2 start pid $$ (cpsam pid $CPSAM)"
declare -A RUN; KAPID=0
while true; do
  [ -f $LANE/STOP_QUEUE ] && { log "STOP_QUEUE found, exiting"; [ $KAPID != 0 ] && kill $KAPID; exit 0; }
  SLOTS=$(cat $LANE/slots_gpu1.txt 2>/dev/null); [[ "$SLOTS" =~ ^[0-9]+$ ]] || SLOTS=1
  for n in "${!RUN[@]}"; do if ! kill -0 ${RUN[$n]} 2>/dev/null; then log "finished $n"; unset RUN[$n]; fi; done
  next=""
  while IFS=$'\t' read -r name args; do
    [ -z "$name" ] && continue; [[ "$name" == \#* ]] && continue
    [ -f $LANE/logs/$name.log ] && continue
    next="$name"; nargs="$args"; break
  done < $LANE/jobs_gpu1.tsv
  if [ -n "$next" ] && [ ${#RUN[@]} -lt $SLOTS ]; then
    if [ $KAPID != 0 ]; then kill $KAPID 2>/dev/null; log "keepalive $KAPID stopped"; KAPID=0; sleep 5; fi
    CUDA_VISIBLE_DEVICES=1 OMP_NUM_THREADS=2 setsid $PY $nargs > $LANE/logs/$next.log 2>&1 < /dev/null &
    RUN[$next]=$!; log "started $next pid $! (slots $SLOTS) : $nargs"; sleep 5; continue
  fi
  if [ -z "$next" ] && [ ${#RUN[@]} -eq 0 ] && [ $KAPID == 0 ] && ! { [ "$CPSAM" != "0" ] && [ -d /proc/$CPSAM ]; }; then
    CUDA_VISIBLE_DEVICES=1 setsid $PY $KA --duty 0.35 > $LANE/logs/keepalive.log 2>&1 < /dev/null & KAPID=$!; log "keepalive started $KAPID"
  fi
  sleep 30
done
